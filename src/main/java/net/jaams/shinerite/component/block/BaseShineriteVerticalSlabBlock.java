package net.jaams.shinerite.component.block;

import javax.annotation.Nullable;

import java.util.function.Supplier;

import net.minecraft.core.BlockPos;
import net.minecraft.core.Direction;
import net.minecraft.nbt.CompoundTag;
import net.minecraft.tags.FluidTags;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.item.context.BlockPlaceContext;
import net.minecraft.world.level.BlockGetter;
import net.minecraft.world.level.Level;
import net.minecraft.world.level.LevelAccessor;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.Mirror;
import net.minecraft.world.level.block.Rotation;
import net.minecraft.world.level.block.SimpleWaterloggedBlock;
import net.minecraft.world.level.block.entity.BlockEntity;
import net.minecraft.world.level.block.entity.BlockEntityType;
import net.minecraft.world.level.block.state.BlockBehaviour;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.block.state.StateDefinition;
import net.minecraft.world.level.block.state.properties.BlockStateProperties;
import net.minecraft.world.level.block.state.properties.BooleanProperty;
import net.minecraft.world.level.block.state.properties.EnumProperty;
import net.minecraft.world.level.material.Fluid;
import net.minecraft.world.level.material.FluidState;
import net.minecraft.world.level.material.Fluids;
import net.minecraft.world.level.pathfinder.PathComputationType;
import net.minecraft.world.phys.Vec3;
import net.minecraft.world.phys.shapes.CollisionContext;
import net.minecraft.world.phys.shapes.Shapes;
import net.minecraft.world.phys.shapes.VoxelShape;
import net.minecraft.util.StringRepresentable;

import net.jaams.shinerite.util.ModUtils;

/**
 * Base for shinerite vertical slabs. Extends {@link BaseShineriteBlock} so dyeing,
 * coating, imbuing, washing, drops, glow and color sync are the native shinerite
 * mechanics backed by a real {@link BaseShineriteBlockEntity}.
 *
 * The vertical-slab geometry (states, placement, double slabs, waterlogging) is
 * implemented here so the mod does not need to depend on Vertical Slabs Compat's
 * block class or Moonlight's {@code CutBlockType}.
 */
public abstract class BaseShineriteVerticalSlabBlock extends BaseShineriteBlock implements SimpleWaterloggedBlock {
	public static final EnumProperty<VerticalSlabType> TYPE = EnumProperty.create("type", VerticalSlabType.class);
	public static final BooleanProperty WATERLOGGED = BlockStateProperties.WATERLOGGED;

	public BaseShineriteVerticalSlabBlock(BlockBehaviour.Properties properties, Supplier<BlockEntityType<?>> blockEntityType) {
		super(properties, blockEntityType);
		this.registerDefaultState(this.defaultBlockState().setValue(TYPE, VerticalSlabType.NORTH).setValue(WATERLOGGED, false));
	}

	@Override
	protected void createBlockStateDefinition(StateDefinition.Builder<Block, BlockState> builder) {
		builder.add(TYPE, WATERLOGGED);
	}

	@Override
	public VoxelShape getShape(BlockState state, BlockGetter level, BlockPos pos, CollisionContext context) {
		return state.getValue(TYPE).shape;
	}

	@Override
	public int getLightBlock(BlockState state, BlockGetter level, BlockPos pos) {
		// Shinerite blocks normally absorb all light, but a single vertical slab only
		// fills half of the block. Keeping 15 there blacks out the empty half (where
		// a second slab would fit). Partial slabs use vanilla light blocking, like
		// the vertical slabs generated by v_slab_compat; a double slab is a full block.
		if (state.getValue(TYPE) == VerticalSlabType.DOUBLE) {
			return super.getLightBlock(state, level, pos);
		}
		return state.isSolidRender(level, pos) ? level.getMaxLightLevel()
			: state.propagatesSkylightDown(level, pos) ? 0 : 1;
	}

	@Override
	public boolean useShapeForLightOcclusion(BlockState state) {
		return state.getValue(TYPE) != VerticalSlabType.DOUBLE;
	}

	@Override
	public BlockState rotate(BlockState state, Rotation rotation) {
		VerticalSlabType type = state.getValue(TYPE);
		if (type == VerticalSlabType.DOUBLE) {
			return state;
		}
		VerticalSlabType rotated = VerticalSlabType.fromDirection(rotation.rotate(type.direction));
		return rotated == null ? state : state.setValue(TYPE, rotated);
	}

	@Override
	public BlockState mirror(BlockState state, Mirror mirror) {
		VerticalSlabType type = state.getValue(TYPE);
		if (type == VerticalSlabType.DOUBLE || mirror == Mirror.NONE) {
			return state;
		}
		boolean flip = (mirror == Mirror.LEFT_RIGHT && type.direction.getAxis() == Direction.Axis.Z)
			|| (mirror == Mirror.FRONT_BACK && type.direction.getAxis() == Direction.Axis.X);
		if (!flip) {
			return state;
		}
		VerticalSlabType mirrored = VerticalSlabType.fromDirection(type.direction.getOpposite());
		return mirrored == null ? state : state.setValue(TYPE, mirrored);
	}

	@Nullable
	@Override
	public BlockState getStateForPlacement(BlockPlaceContext context) {
		BlockPos pos = context.getClickedPos();
		Level level = context.getLevel();
		BlockState existing = level.getBlockState(pos);
		int handColor = ModUtils.getCurrentColor(context.getItemInHand());

		if (existing.getBlock() == this) {
			// Only combine matching colors, mirroring the horizontal shinerite slab behavior.
			if (getColorAt(level, pos) != handColor) {
				return null;
			}
			return existing.setValue(TYPE, VerticalSlabType.DOUBLE).setValue(WATERLOGGED, false);
		}

		FluidState fluid = level.getFluidState(pos);
		BlockState state = this.defaultBlockState().setValue(WATERLOGGED, fluid.getType() == Fluids.WATER);
		VerticalSlabType type = VerticalSlabType.fromDirection(getDirectionForPlacement(context));
		return state.setValue(TYPE, type == null ? VerticalSlabType.NORTH : type);
	}

	@Override
	public boolean canBeReplaced(BlockState state, BlockPlaceContext context) {
		VerticalSlabType type = state.getValue(TYPE);
		ItemStack stack = context.getItemInHand();
		if (type == VerticalSlabType.DOUBLE || stack.getItem() != this.asItem()) {
			return false;
		}
		if (getColorAt(context.getLevel(), context.getClickedPos()) != ModUtils.getCurrentColor(stack)) {
			return false;
		}
		if (context.replacingClickedOnBlock()) {
			return context.getClickedFace() == type.direction && getDirectionForPlacement(context) != type.direction;
		}
		return context.getClickedFace() != type.direction;
	}

	private int getColorAt(Level level, BlockPos pos) {
		BlockEntity blockEntity = level.getBlockEntity(pos);
		return blockEntity instanceof BaseShineriteBlockEntity shineriteBlockEntity ? shineriteBlockEntity.getColor() : -1;
	}

	private Direction getDirectionForPlacement(BlockPlaceContext context) {
		Direction face = context.getClickedFace();
		if (face.getAxis() != Direction.Axis.Y) {
			return face;
		}
		BlockPos pos = context.getClickedPos();
		Vec3 hit = context.getClickLocation()
			.subtract(new Vec3(pos.getX(), pos.getY(), pos.getZ()))
			.subtract(0.5D, 0.5D, 0.5D);
		float angle = (float) (Math.atan2(hit.x, hit.z) * -180.0D / Math.PI);
		return Direction.fromYRot(angle).getOpposite();
	}

	@Override
	public FluidState getFluidState(BlockState state) {
		return state.getValue(WATERLOGGED) ? Fluids.WATER.getSource(false) : super.getFluidState(state);
	}

	@Override
	public boolean placeLiquid(LevelAccessor level, BlockPos pos, BlockState state, FluidState fluidState) {
		return state.getValue(TYPE) != VerticalSlabType.DOUBLE
			&& SimpleWaterloggedBlock.super.placeLiquid(level, pos, state, fluidState);
	}

	@Override
	public boolean canPlaceLiquid(BlockGetter level, BlockPos pos, BlockState state, Fluid fluid) {
		return state.getValue(TYPE) != VerticalSlabType.DOUBLE
			&& SimpleWaterloggedBlock.super.canPlaceLiquid(level, pos, state, fluid);
	}

	@Override
	public BlockState updateShape(BlockState state, Direction direction, BlockState neighborState, LevelAccessor level, BlockPos pos, BlockPos neighborPos) {
		if (state.getValue(WATERLOGGED)) {
			level.scheduleTick(pos, Fluids.WATER, Fluids.WATER.getTickDelay(level));
		}
		return super.updateShape(state, direction, neighborState, level, pos, neighborPos);
	}

	@Override
	public boolean isPathfindable(BlockState state, BlockGetter level, BlockPos pos, PathComputationType type) {
		return type == PathComputationType.WATER && level.getFluidState(pos).is(FluidTags.WATER);
	}

	public enum VerticalSlabType implements StringRepresentable {
		NORTH(Direction.NORTH),
		SOUTH(Direction.SOUTH),
		WEST(Direction.WEST),
		EAST(Direction.EAST),
		DOUBLE(null);

		@Nullable
		public final Direction direction;
		public final VoxelShape shape;
		private final String name;

		VerticalSlabType(@Nullable Direction direction) {
			this.direction = direction;
			this.name = direction == null ? "double" : direction.getSerializedName();
			if (direction == null) {
				this.shape = Shapes.block();
			} else {
				double min = 0.0D;
				double max = 8.0D;
				if (direction.getAxisDirection() == Direction.AxisDirection.NEGATIVE) {
					min = 8.0D;
					max = 16.0D;
				}
				if (direction.getAxis() == Direction.Axis.X) {
					this.shape = Block.box(min, 0.0D, 0.0D, max, 16.0D, 16.0D);
				} else {
					this.shape = Block.box(0.0D, 0.0D, min, 16.0D, 16.0D, max);
				}
			}
		}

		@Nullable
		public static VerticalSlabType fromDirection(@Nullable Direction direction) {
			for (VerticalSlabType type : values()) {
				if (type.direction == direction) {
					return type;
				}
			}
			return null;
		}

		@Override
		public String getSerializedName() {
			return this.name;
		}
	}
}
